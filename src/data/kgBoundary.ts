// Ray casting: точка внутри полигона?
export function isInsideKyrgyzstan(lng: number, lat: number): boolean {
  let inside = false;
  const n = KG_BOUNDARY.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const [xi, yi] = KG_BOUNDARY[i];
    const [xj, yj] = KG_BOUNDARY[j];
    const intersects =
      yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}
